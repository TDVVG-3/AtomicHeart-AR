<#
.SYNOPSIS
  Builds a batch-2 chunk file from a stable-id Arabic side file (DEC-027 contract).

.DESCRIPTION
  Input : localization/working/batch2/plan_unique.tsv   (id, english, ...)  generated by batch2_plan.ps1
          localization/working/batch2/ar_<nnnn>.tsv     (id<TAB>arabic)     authored by hand
  Output: localization/working/batch2/chunk_<nnnn>.tsv (english<TAB>arabic<TAB>note)

  The English column is copied from plan_unique.tsv by id, never retyped, so an
  English cell can never drift from the master.

  Hard checks (abort, exit 1):
    - unknown id / duplicate id
    - empty Arabic, or Arabic without a single Arabic letter (copy-class rows must be omitted)
    - placeholder / timing-marker / tag multiset mismatch between English and Arabic
  Warning only: Arabic longer than 1.6 x English (possible subtitle overflow risk).

  ASCII-only script; all Arabic stays in the UTF-8 data files.
#>
[CmdletBinding()]
param(
    [string]$RepoRoot = 'C:\AtomicHeart-AR',
    [Parameter(Mandatory = $true)][string]$ChunkId
)
$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch {}
trap { Write-Output ('ERROR at line ' + $_.InvocationInfo.ScriptLineNumber + ': ' + $_.Exception.Message); exit 1 }

$work   = Join-Path $RepoRoot 'localization\working\batch2'
$planP  = Join-Path $work 'plan_unique.tsv'
$arP    = Join-Path $work ('ar_' + $ChunkId + '.tsv')
$outP   = Join-Path $work ('chunk_' + $ChunkId + '.tsv')
$utf8   = New-Object Text.UTF8Encoding($false)
foreach ($p in @($planP, $arP)) { if (-not (Test-Path $p)) { throw ('missing input: ' + $p) } }

# plan ids -> english (ordinal)
$en = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::Ordinal)
$order = New-Object System.Collections.Generic.List[string]
$pl = [IO.File]::ReadAllLines($planP, [Text.Encoding]::UTF8)
for ($i = 1; $i -lt $pl.Count; $i++) {
    if (-not $pl[$i].Trim()) { continue }
    $f = $pl[$i] -split "`t"
    if ($f.Count -lt 2) { continue }
    $en[$f[0]] = $f[1]
    $order.Add($f[0])
}

$arRe = '[\u0600-\u06FF]'
$rows = New-Object System.Collections.Generic.List[object]
$seen = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
$al = [IO.File]::ReadAllLines($arP, [Text.Encoding]::UTF8)
for ($i = 0; $i -lt $al.Count; $i++) {
    if (-not $al[$i].Trim()) { continue }
    $f = $al[$i] -split "`t"
    $id = $f[0]
    if ($id -eq 'id') { continue }
    if (-not $en.ContainsKey($id)) { throw ('ar line ' + ($i + 1) + ': unknown id [' + $id + ']') }
    if (-not $seen.Add($id)) { throw ('ar line ' + ($i + 1) + ': duplicate id [' + $id + ']') }
    $va = ''
    if ($f.Count -ge 2) { $va = $f[1] }
    $ve = $en[$id]
    if (-not $va.Trim()) { throw ('[' + $id + '] empty Arabic') }
    if ($va -notmatch $arRe) { throw ('[' + $id + '] Arabic cell has no Arabic letters - copy-class rows must be omitted: ' + $va) }
    # token multiset comparison.
    # Bracket labels may be localized ([Leave] -> [مغادرة]) - that is the KI-029/DEC-039 exception.
    # Everything else must survive byte-exact, and the bracket count must still match, so a dropped
    # or invented bracket token is still a hard failure.
    # the timing-marker pattern is the validator's one: it also covers RANGE markers such as *0.01-0.28*
    $patNon = '(\*[0-9][0-9.\-]*\*)|(\{[^}]*\})|(<[^>]{1,24}>)|(&[A-Za-z]{1,16}&)|(\\n)'
    $patBrk = '\[[^\]]{1,40}\]'
    $te = ($ve | Select-String -AllMatches -Pattern $patNon).Matches | ForEach-Object { $_.Value } | Sort-Object
    $ta = ($va | Select-String -AllMatches -Pattern $patNon).Matches | ForEach-Object { $_.Value } | Sort-Object
    if ((($te -join '|') -cne ($ta -join '|'))) {
        throw ('[' + $id + '] token mismatch EN=[' + ($te -join ',') + '] AR=[' + ($ta -join ',') + ']')
    }
    $tb = @(($ve | Select-String -AllMatches -Pattern $patBrk).Matches | Where-Object { $_ } | ForEach-Object { $_.Value })
    $ab = @(($va | Select-String -AllMatches -Pattern $patBrk).Matches | Where-Object { $_ } | ForEach-Object { $_.Value })
    if ($tb.Count -ne $ab.Count) {
        throw ('[' + $id + '] bracket token count mismatch EN=[' + ($tb -join ',') + '] AR=[' + ($ab -join ',') + ']')
    }
    if ($tb.Count -gt 0) {
        $sbt = @($tb | Sort-Object)
        $sba = @($ab | Sort-Object)
        for ($bi = 0; $bi -lt $tb.Count; $bi++) {
            if (($sba[$bi] -cne $sbt[$bi]) -and ($sba[$bi] -notmatch $arRe)) {
                throw ('[' + $id + '] bracket token changed without an Arabic label? EN=[' + $sbt[$bi] + '] AR=[' + $sba[$bi] + ']')
            }
        }
    }
    if ($va.Length -gt [Math]::Ceiling($ve.Length * 1.6)) { Write-Output ('[warn] ' + $id + ': AR ' + $va.Length + ' chars vs EN ' + $ve.Length) }
    $rows.Add([pscustomobject]@{ id = $id; english = $ve; arabic = $va })
}

$out = New-Object System.Collections.Generic.List[string]
$out.Add(('english' + "`t" + 'arabic' + "`t" + 'note'))
foreach ($r in $rows) { $out.Add(($r.english + "`t" + $r.arabic + "`t" + ('batch2-' + $ChunkId))) }
[IO.File]::WriteAllLines($outP, $out, $utf8)
Write-Output ('[chunk ' + $ChunkId + '] entries: ' + $rows.Count + ' -> ' + $outP)
$miss = New-Object System.Collections.Generic.List[string]
foreach ($id in $order[0..([Math]::Min($order.Count, $rows.Count) - 1)]) { if (-not $seen.Contains($id)) { $miss.Add($id) } }
if ($miss.Count -gt 0) { Write-Output ('[chunk ' + $ChunkId + '] NOTE: ids inside the covered range not yet authored: ' + ($miss -join ', ')) }
